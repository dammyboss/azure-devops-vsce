#!/usr/bin/env node

/**
 * Azure DevOps Test Data Generator
 *
 * Creates test work items and sprints for testing the board view with iteration filters.
 *
 * Usage:
 *   node scripts/generate-test-data.js create
 *   node scripts/generate-test-data.js cleanup
 *
 * Requirements:
 *   - Set environment variables: ADO_ORG_URL, ADO_PROJECT, ADO_TEAM, ADO_PAT
 *   - Or configure them in the script below
 */

const https = require('https');
const { URL } = require('url');

// ============ CONFIGURATION ============
const config = {
    organizationUrl: process.env.ADO_ORG_URL || 'https://dev.azure.com/your-org',
    project: process.env.ADO_PROJECT || 'YourProject',
    team: process.env.ADO_TEAM || 'YourTeam',
    pat: process.env.ADO_PAT || 'your-pat-here'
};

// Test data tag to identify created items for cleanup
const TEST_TAG = 'TestData-AutoGenerated';

// Work item types to create
const WORK_ITEM_TYPES = [
    { type: 'User Story', count: 3 },
    { type: 'Bug', count: 1 },
    { type: 'Task', count: 1 }
];

// ============ UTILITY FUNCTIONS ============

/**
 * Make an authenticated HTTP request to Azure DevOps API
 */
function makeRequest(method, path, data = null) {
    return new Promise((resolve, reject) => {
        const urlObj = new URL(path, config.organizationUrl);
        const auth = Buffer.from(':' + config.pat).toString('base64');

        const options = {
            hostname: urlObj.hostname,
            port: 443,
            path: urlObj.pathname + urlObj.search,
            method: method,
            headers: {
                'Authorization': `Basic ${auth}`,
                'Content-Type': 'application/json-patch+json',
                'Accept': 'application/json'
            }
        };

        const req = https.request(options, (res) => {
            let body = '';
            res.on('data', (chunk) => body += chunk);
            res.on('end', () => {
                if (res.statusCode >= 200 && res.statusCode < 300) {
                    try {
                        resolve(JSON.parse(body));
                    } catch (e) {
                        resolve(body);
                    }
                } else {
                    reject(new Error(`HTTP ${res.statusCode}: ${body}`));
                }
            });
        });

        req.on('error', reject);
        if (data) req.write(JSON.stringify(data));
        req.end();
    });
}

/**
 * Get a date string in ISO format
 */
function getDateString(daysOffset) {
    const date = new Date();
    date.setDate(date.getDate() + daysOffset);
    return date.toISOString();
}

/**
 * Format date for display
 */
function formatDate(dateStr) {
    return new Date(dateStr).toLocaleDateString();
}

// ============ SPRINT MANAGEMENT ============

/**
 * Get existing iterations
 */
async function getIterations() {
    console.log('\n📅 Fetching existing iterations...');
    const path = `/${encodeURIComponent(config.project)}/${encodeURIComponent(config.team)}/_apis/work/teamsettings/iterations?api-version=7.1`;
    const response = await makeRequest('GET', path);
    return response.value || [];
}

/**
 * Create iterations (sprints) with one being current
 */
async function createIterations() {
    console.log('\n🏗️  Creating 5 test sprints...');

    const iterations = [];
    const sprintDuration = 14; // 2 weeks per sprint

    // Sprint schedule:
    // Sprint 1: Past (ended 30 days ago)
    // Sprint 2: Past (ended 16 days ago)
    // Sprint 3: Current (started 7 days ago, ends in 7 days)
    // Sprint 4: Future (starts in 8 days)
    // Sprint 5: Future (starts in 22 days)

    const sprintSchedule = [
        { name: 'Test Sprint 1', start: -44, end: -30 },  // Past
        { name: 'Test Sprint 2', start: -30, end: -16 },  // Past
        { name: 'Test Sprint 3', start: -7, end: 7 },     // Current (includes today)
        { name: 'Test Sprint 4', start: 8, end: 22 },     // Future
        { name: 'Test Sprint 5', start: 22, end: 36 }     // Future
    ];

    for (const sprint of sprintSchedule) {
        const startDate = getDateString(sprint.start);
        const endDate = getDateString(sprint.end);

        const isCurrent = sprint.start <= 0 && sprint.end >= 0;
        const status = isCurrent ? '🟢 CURRENT' : (sprint.end < 0 ? '⚪ Past' : '🔵 Future');

        console.log(`  Creating: ${sprint.name} (${status})`);
        console.log(`    Dates: ${formatDate(startDate)} - ${formatDate(endDate)}`);

        try {
            // First, create the iteration path in project settings
            const iterationPath = `${config.project}\\${sprint.name}`;

            // Note: Creating iterations via API requires admin permissions
            // For now, we'll store the iteration info to create work items with
            iterations.push({
                name: sprint.name,
                path: iterationPath,
                startDate: startDate,
                finishDate: endDate,
                isCurrent: isCurrent
            });

            console.log(`    ✓ Configured ${sprint.name}`);
        } catch (error) {
            console.error(`    ✗ Failed to create ${sprint.name}:`, error.message);
            console.log(`    💡 You may need to manually create iteration path in Azure DevOps:`);
            console.log(`       Project Settings > Project Configuration > Iterations`);
        }
    }

    return iterations;
}

// ============ WORK ITEM MANAGEMENT ============

/**
 * Create a work item
 */
async function createWorkItem(type, title, iterationPath, description, acceptanceCriteria) {
    const patchDocument = [
        { op: 'add', path: '/fields/System.Title', value: title },
        { op: 'add', path: '/fields/System.IterationPath', value: iterationPath },
        { op: 'add', path: '/fields/System.Description', value: description },
        { op: 'add', path: '/fields/System.Tags', value: TEST_TAG }
    ];

    // Add acceptance criteria for User Stories
    if (type === 'User Story' && acceptanceCriteria) {
        patchDocument.push({
            op: 'add',
            path: '/fields/Microsoft.VSTS.Common.AcceptanceCriteria',
            value: acceptanceCriteria
        });
    }

    const path = `/${encodeURIComponent(config.project)}/_apis/wit/workitems/$${encodeURIComponent(type)}?api-version=7.1`;
    return await makeRequest('POST', path, patchDocument);
}

/**
 * Generate test description
 */
function generateDescription(type, sprintName, index) {
    const descriptions = {
        'User Story': `
            <h3>User Story: ${sprintName} - Item ${index}</h3>
            <p>As a user, I want to be able to test the board view with iteration filters,
            so that I can verify the functionality works correctly.</p>
            <p><strong>Background:</strong> This is a test user story created automatically
            to populate the board with realistic data for testing purposes.</p>
            <ul>
                <li>Sprint: ${sprintName}</li>
                <li>Type: ${type}</li>
                <li>Index: ${index}</li>
            </ul>
        `,
        'Bug': `
            <h3>Bug: ${sprintName} - Item ${index}</h3>
            <p><strong>Steps to Reproduce:</strong></p>
            <ol>
                <li>Open the application</li>
                <li>Navigate to the test page</li>
                <li>Observe the issue</li>
            </ol>
            <p><strong>Expected Result:</strong> Feature should work correctly</p>
            <p><strong>Actual Result:</strong> This is a test bug for demonstration</p>
        `,
        'Task': `
            <h3>Task: ${sprintName} - Item ${index}</h3>
            <p>This is a test task for ${sprintName}. It demonstrates how tasks appear
            on the board and can be filtered by iteration.</p>
            <p><strong>Steps:</strong></p>
            <ul>
                <li>Review requirements</li>
                <li>Implement solution</li>
                <li>Test thoroughly</li>
            </ul>
        `
    };

    return descriptions[type] || `<p>Test ${type} for ${sprintName}</p>`;
}

/**
 * Generate acceptance criteria
 */
function generateAcceptanceCriteria(sprintName, index) {
    return `
        <h4>Acceptance Criteria:</h4>
        <ul>
            <li><strong>Given</strong> a user is viewing the board</li>
            <li><strong>When</strong> they filter by ${sprintName}</li>
            <li><strong>Then</strong> this work item should appear in the results</li>
        </ul>
        <h4>Definition of Done:</h4>
        <ul>
            <li>Code is written and reviewed</li>
            <li>Unit tests pass</li>
            <li>Integration tests pass</li>
            <li>Documentation is updated</li>
        </ul>
    `;
}

/**
 * Create work items for all sprints
 */
async function createWorkItems(iterations) {
    console.log('\n📝 Creating work items...');
    const createdItems = [];
    let totalCreated = 0;

    for (const iteration of iterations) {
        const status = iteration.isCurrent ? '🟢 CURRENT' : '  ';
        console.log(`\n  ${status} Sprint: ${iteration.name}`);

        let itemIndex = 1;

        // Create different types of work items
        for (const workItemType of WORK_ITEM_TYPES) {
            for (let i = 0; i < workItemType.count; i++) {
                const title = `${workItemType.type}: ${iteration.name} - Item ${itemIndex}`;
                const description = generateDescription(workItemType.type, iteration.name, itemIndex);
                const acceptanceCriteria = workItemType.type === 'User Story'
                    ? generateAcceptanceCriteria(iteration.name, itemIndex)
                    : null;

                try {
                    const workItem = await createWorkItem(
                        workItemType.type,
                        title,
                        iteration.path,
                        description,
                        acceptanceCriteria
                    );

                    console.log(`    ✓ Created ${workItemType.type} #${workItem.id}: ${title}`);
                    createdItems.push(workItem);
                    totalCreated++;
                    itemIndex++;
                } catch (error) {
                    console.error(`    ✗ Failed to create ${workItemType.type}:`, error.message);
                }

                // Small delay to avoid rate limiting
                await new Promise(resolve => setTimeout(resolve, 100));
            }
        }
    }

    console.log(`\n✅ Total work items created: ${totalCreated}`);
    return createdItems;
}

/**
 * Find all test work items by tag
 */
async function findTestWorkItems() {
    console.log(`\n🔍 Finding all work items with tag: ${TEST_TAG}...`);

    const wiql = {
        query: `SELECT [System.Id] FROM WorkItems WHERE [System.Tags] Contains '${TEST_TAG}' AND [System.TeamProject] = '${config.project}'`
    };

    const path = `/${encodeURIComponent(config.project)}/_apis/wit/wiql?api-version=7.1`;
    const response = await makeRequest('POST', path, wiql);

    const workItemIds = (response.workItems || []).map(wi => wi.id);
    console.log(`  Found ${workItemIds.length} test work items`);

    return workItemIds;
}

/**
 * Delete work items
 */
async function deleteWorkItems(workItemIds) {
    if (workItemIds.length === 0) {
        console.log('\n  No work items to delete');
        return;
    }

    console.log(`\n🗑️  Deleting ${workItemIds.length} work items...`);

    let deleted = 0;
    for (const id of workItemIds) {
        try {
            const path = `/${encodeURIComponent(config.project)}/_apis/wit/workitems/${id}?api-version=7.1`;
            await makeRequest('DELETE', path);
            console.log(`  ✓ Deleted work item #${id}`);
            deleted++;

            // Small delay to avoid rate limiting
            await new Promise(resolve => setTimeout(resolve, 100));
        } catch (error) {
            console.error(`  ✗ Failed to delete work item #${id}:`, error.message);
        }
    }

    console.log(`\n✅ Deleted ${deleted} work items`);
}

