/**
 * Clean up all test data
 */
async function cleanupTestData() {
    console.log('\n╔════════════════════════════════════════╗');
    console.log('║      Test Data Cleanup Started         ║');
    console.log('╚════════════════════════════════════════╝');
    console.log(`\nSearching for work items tagged: ${TEST_TAG}`);

    try {
        const workItemIds = await findTestWorkItems();

        if (workItemIds.length === 0) {
            console.log('\n✅ No test work items found. Already clean!');
            return;
        }

        console.log(`\n⚠️  About to delete ${workItemIds.length} work items!`);
        console.log('Waiting 3 seconds... Press Ctrl+C to cancel');
        await new Promise(resolve => setTimeout(resolve, 3000));

        await deleteWorkItems(workItemIds);

        console.log('\n╔════════════════════════════════════════╗');
        console.log('║         Cleanup Complete!              ║');
        console.log('╚════════════════════════════════════════╝');
        console.log('\n✅ All test work items have been deleted');
        console.log('\n💡 Note: Iteration paths are not deleted. To remove them:');
        console.log('   Project Settings > Boards > Project Configuration > Iterations');

    } catch (error) {
        console.error('\n❌ Error:', error.message);
        process.exit(1);
    }
}

